#!/usr/bin/env python
"""Rebuild manifests and digest every downloaded file.

Two modes:
  --hash    walk data/raw and rewrite data/manifests/sha256.txt
  (default) print the counts we can verify without the payload
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--hash", action="store_true", help="rewrite sha256.txt from data/raw")
    args = ap.parse_args()

    raw = ROOT / "data" / "raw"
    files = sorted(p for p in raw.rglob("*") if p.is_file() and p.name != ".gitkeep")

    if args.hash:
        if not files:
            print("data/raw is empty; nothing to hash. Run 00_fetch_data.sh first.")
            return 1
        out = ROOT / "data" / "manifests" / "sha256.txt"
        lines = ["# generated by scripts/01_build_manifests.py --hash on %s" % "D0", ""]
        for f in files:
            lines.append("%s  %s" % (sha256(f), f.relative_to(raw).as_posix()))
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote", out, "with", len(files), "entries")
        return 0

    print("data/raw files:", len(files))
    print("PolyBench tasks expected: 39 (42,169 records)")
    print("OpenPoly expected: 741 structures / 3,985 labels / 26 properties")
    print("Run with --hash once the downloads are in place.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
